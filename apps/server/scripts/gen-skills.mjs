// Compiles skills/*/SKILL.md, and skills/retired.json for upgrading older libraries, into src/bundledSkills.ts so the
// single-binary engine can seed them without a skills directory on disk. Skill names live in those files, never in code.
import { readdirSync, readFileSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const skillsDir = resolve(here, "../../../skills");
const out = resolve(here, "../src/bundledSkills.ts");
const list = [];
if (existsSync(skillsDir)) {
  for (const entry of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const file = join(skillsDir, entry.name, "SKILL.md");
    if (existsSync(file)) list.push({ folder: entry.name, content: readFileSync(file, "utf8") });
  }
}
const retiredFile = join(skillsDir, "retired.json");
const { about: _about, ...retired } = existsSync(retiredFile) ? JSON.parse(readFileSync(retiredFile, "utf8")) : {};
const empty = { renamed: {}, workflows: { names: [], replacedBy: {}, revisions: [] }, guides: { names: [], revisions: [] }, shortcuts: { revisions: [] } };
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// Generated by scripts/gen-skills.mjs from skills/*/SKILL.md and skills/retired.json. Do not edit.\n" +
    "export const BUNDLED_SKILLS: Array<{ folder: string; content: string }> = " +
    JSON.stringify(list, null, 2) +
    ";\n\n" +
    "/** Skills Scarlet used to ship (skills/retired.json): what upgrading an older library needs to know about them. */\n" +
    "export const RETIRED_SKILLS: {\n" +
    "  renamed: Record<string, { to: string; seedRevisions?: string[] }>;\n" +
    "  workflows: { names: string[]; replacedBy: Record<string, string>; revisions: string[] };\n" +
    "  guides: { names: string[]; revisions: string[] };\n" +
    "  shortcuts: { movesTo?: string; revisions: string[] };\n" +
    "} = " +
    JSON.stringify({ ...empty, ...retired }, null, 2) +
    ";\n",
);
console.log(`[gen-skills] bundled ${list.length} skill(s) into src/bundledSkills.ts`);
