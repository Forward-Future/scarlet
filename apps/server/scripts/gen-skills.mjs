// Compiles skills/*/SKILL.md into src/bundledSkills.ts so the single-binary
// engine can seed them without a skills directory on disk.
import { readdirSync, readFileSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const skillsDir = resolve(here, "../../../skills");
const out = resolve(here, "../src/bundledSkills.ts");
const list = [];
if (existsSync(skillsDir)) {
  for (const entry of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const file = join(skillsDir, entry.name, "SKILL.md");
    if (existsSync(file)) list.push({ folder: entry.name, content: readFileSync(file, "utf8") });
  }
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// Generated by scripts/gen-skills.mjs from skills/*/SKILL.md. Do not edit.\n" +
    "export const BUNDLED_SKILLS: Array<{ folder: string; content: string }> = " +
    JSON.stringify(list, null, 2) +
    ";\n",
);
console.log(`[gen-skills] bundled ${list.length} skill(s) into src/bundledSkills.ts`);
